import fs from 'fs';
import path from 'path';
import { ALLOCATION_FIELDS, STRATEGY_DOCS } from './allocationFields.js';
import {
  checkSettings,
  renderConfigFieldTables,
  renderEnvExample,
  renderSettingsTable,
  renderStrategiesTable,
  replaceBetweenMarkers,
  scanEnvReads,
  scanInlineDefaults,
} from './schema.js';
import { settingsList } from './settings.js';

/** Process-level variables that the code reads but that are not bot settings. */
export const ENV_READ_ALLOW_LIST = ['NODE_ENV', 'TZ', 'NODE_OPTIONS'];

/** The logger cannot import the registry. A parity test pins its allowed inline default. */
export const INLINE_DEFAULT_ALLOWED_PATHS = ['logger/src/'];

const SCANNED_DIRS = ['investing-bot/src', 'tx/src', 'logger/src'];
const ENV_EXAMPLE_FILE = '.env.example';
const README_FILE = 'README.md';
const SETTINGS_MARKERS = ['<!-- settings:start -->', '<!-- settings:end -->'] as const;
const ALLOCATION_FIELDS_MARKERS = ['<!-- allocation-fields:start -->', '<!-- allocation-fields:end -->'] as const;
const STRATEGIES_MARKERS = ['<!-- strategies:start -->', '<!-- strategies:end -->'] as const;

const ENV_EXAMPLE_HEADER = `# Generated by \`yarn config:generate\` from investing-bot/src/config/settings.ts. Do not edit by hand.
# \`yarn config:check\` verifies in CI that this file, the README tables and the code agree.
# Copy this file to .env.<PROFILE>. Uncommented lines are a starting profile; commented lines show the defaults.
# Shell-level variables such as NODE_OPTIONS belong in the Dockerfile, the helm chart or the shell, not here.`;

const VAULT_FIELDS_HEADING =
  '**Vault-object fields** (use an object instead of a plain address string when a vault needs fixed reserves or its own overrides)';

function renderReadme(currentReadme: string): string {
  const withSettings = replaceBetweenMarkers(
    currentReadme,
    SETTINGS_MARKERS[0],
    SETTINGS_MARKERS[1],
    renderSettingsTable(settingsList())
  );
  const withStrategies = replaceBetweenMarkers(
    withSettings,
    STRATEGIES_MARKERS[0],
    STRATEGIES_MARKERS[1],
    renderStrategiesTable(STRATEGY_DOCS)
  );
  return replaceBetweenMarkers(
    withStrategies,
    ALLOCATION_FIELDS_MARKERS[0],
    ALLOCATION_FIELDS_MARKERS[1],
    renderConfigFieldTables(ALLOCATION_FIELDS, {
      entry: '**Entry fields**',
      both: '**Entry or vault-object fields** (set on the entry or on a vault object; the vault value wins)',
      vault: VAULT_FIELDS_HEADING,
    })
  );
}

function generatedFiles(repoRoot: string): Map<string, string> {
  const readme = fs.readFileSync(path.join(repoRoot, README_FILE), 'utf8');
  return new Map([
    [ENV_EXAMPLE_FILE, renderEnvExample(settingsList(), ENV_EXAMPLE_HEADER)],
    [README_FILE, renderReadme(readme)],
  ]);
}

/** Writes `.env.example` and rewrites the README between its markers. */
export function generateConfigDocs(repoRoot: string): void {
  for (const [file, content] of generatedFiles(repoRoot)) {
    fs.writeFileSync(path.join(repoRoot, file), content);
  }
}

function firstDifference(file: string, expected: string, actual: string): string | undefined {
  if (expected === actual) {
    return undefined;
  }
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  let line = 0;
  while (line < expectedLines.length && expectedLines[line] === actualLines[line]) {
    line++;
  }
  const expectedLine = expectedLines[line] ?? '<end of file>';
  const actualLine = actualLines[line] ?? '<end of file>';
  return `${file}:${line + 1} is out of date; run yarn config:generate. Expected "${expectedLine}", found "${actualLine}"`;
}

/** Returns every disagreement between the code, the registry and the generated files. Writes nothing. */
function relativeLocations(scanned: Map<string, string[]>, repoRoot: string): Map<string, string[]> {
  return new Map(
    [...scanned.entries()].map(([name, locations]) => [
      name,
      locations.map((location) => path.relative(repoRoot, location)),
    ])
  );
}

export function checkConfigDocs(repoRoot: string): string[] {
  const scannedDirs = SCANNED_DIRS.map((dir) => path.join(repoRoot, dir));
  const problems = checkSettings({
    settings: settingsList(),
    reads: relativeLocations(scanEnvReads(scannedDirs), repoRoot),
    allowList: ENV_READ_ALLOW_LIST,
    inlineDefaults: relativeLocations(scanInlineDefaults(scannedDirs), repoRoot),
    inlineDefaultAllowedPaths: INLINE_DEFAULT_ALLOWED_PATHS,
  });

  let generated: Map<string, string>;
  try {
    generated = generatedFiles(repoRoot);
  } catch (error) {
    return [...problems, `${README_FILE}: ${error instanceof Error ? error.message : String(error)}`];
  }
  for (const [file, expected] of generated) {
    const filePath = path.join(repoRoot, file);
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
    const difference = firstDifference(file, expected, actual);
    if (difference !== undefined) {
      problems.push(difference);
    }
  }
  return problems;
}
